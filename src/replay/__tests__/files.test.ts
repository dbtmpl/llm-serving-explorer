import { readFileSync, readdirSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { parseReplay, type ReplayFile } from "../schema.js";
import { REPLAY_IDS, REPLAY_TITLES } from "../scenarios.js";

const DIR = path.resolve(__dirname, "../../../public/replay");
const LOCK = path.resolve(__dirname, "../../../conformance/refs/blis/lock");

/** The commit named by conformance/refs/blis/lock: its first line that is not a comment. */
const locked = readFileSync(LOCK, "utf8")
  .split("\n")
  .map((l) => l.trim())
  .find((l) => l && !l.startsWith("#"));

const files = new Map<string, ReplayFile>(readdirSync(DIR).filter((f) => f.endsWith(".json")).map((f) => [path.basename(f, ".json"), parseReplay(JSON.parse(readFileSync(path.join(DIR, f), "utf8")))]));

describe("committed replay files", () => {
  it("are exactly the scenarios the site offers", () => {
    expect([...files.keys()].sort()).toEqual([...REPLAY_IDS].sort());
  });

  it("were generated by the commit in conformance/refs/blis/lock", () => {
    expect(locked).toMatch(/^[0-9a-f]{40}$/);
    for (const f of files.values()) expect(f.blis.commit, f.id).toBe(locked);
  });

  it("have the title the picker shows", () => {
    for (const f of files.values()) expect(f.title).toBe(REPLAY_TITLES[f.id as keyof typeof REPLAY_TITLES]);
  });

  it("carry the file name as their id", () => {
    for (const [name, f] of files) expect(f.id).toBe(name);
  });

  it("stay small enough to be served as plain JSON", () => {
    for (const name of files.keys()) expect(readFileSync(path.join(DIR, `${name}.json`)).length, name).toBeLessThan(100 * 1024);
  });

  it("route every completed request to the pod with the highest weighted score", () => {
    for (const f of files.values()) {
      for (const r of f.requests) {
        if (r.fate !== "completed" || !r.scores) continue;
        const totals = r.scores.map((row) => (row ? row.reduce((s, v, k) => s + v * f.scorers[k]!.weight, 0) : -Infinity));
        expect(totals[r.pod!]!, `${f.id} request ${r.id}`).toBeGreaterThanOrEqual(Math.max(...totals) - 1e-6);
      }
    }
  });

  it("never serve more cached tokens than the prompt has", () => {
    for (const f of files.values()) for (const r of f.requests) expect(r.cachedTokens).toBeLessThanOrEqual(r.inputTokens);
  });

  it("show what each scenario is for", () => {
    const get = (id: string) => files.get(id)!;
    const followUps = (f: ReplayFile) => {
      const last = new Map<number, number | null>();
      let back = 0;
      let all = 0;
      for (const r of f.requests) {
        if (r.round > 0) {
          all++;
          if (last.get(r.session) === r.pod) back++;
        }
        last.set(r.session, r.pod);
      }
      return { back, all };
    };
    const a = followUps(get("prefix-followups"));
    expect(a.back / a.all).toBeGreaterThan(0.7);
    expect(get("overload-shedding").totals.shed).toBeGreaterThan(0);
    expect(get("overload-shedding").requests.some((r) => r.fate === "completed" && r.dispatch! - r.arrival > 1)).toBe(true);
    expect(get("kv-pressure").totals.preemptions).toBeGreaterThan(0);
    expect(get("kv-pressure").requests.some((r) => r.preemptedAt !== null)).toBe(true);
    const b = get("steady-chat-70b");
    expect(b.params.tp).toBe(4);
    expect(b.params.replicas).toBe(2);
  });
});
